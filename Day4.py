print("Operações Aritméticas")
print(f"Adição: {numero1 + numero2}")
print(f"Subtração: {numero1 - numero2}")
print(f"Multiplicação: {numero1 * numero2}")
print(f"Divisão: {numero1 / numero2}")
print(f"Divisão Inteira: {numero1 // numero2}")
